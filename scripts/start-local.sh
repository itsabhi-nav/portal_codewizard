#!/usr/bin/env bash
#
# Start the full CodeWizard stack locally:
#   Postgres + PostgREST + local Supabase proxy + Next.js
#
# Usage: bash scripts/start-local.sh
#
set -euo pipefail

PGHOST="${PGHOST:-localhost}"
PGPORT="${PGPORT:-5432}"
PGUSER="${PGUSER:-$(whoami)}"
PGDATABASE="${PGDATABASE:-codewizard_local}"
BACKEND_PORT="${BACKEND_PORT:-3006}"
PROXY_PORT="${PROXY_PORT:-3005}"
APP_PORT="${APP_PORT:-3200}"
JWT_SECRET="${JWT_SECRET:-local-dev-jwt-secret-with-32-chars-min}"
ADMIN_USERNAME="${ADMIN_USERNAME:-admin}"
ADMIN_PASSWORD="${ADMIN_PASSWORD:-CodeWizard@2026}"
APP_URL="${APP_URL:-http://localhost:${APP_PORT}}"

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT_DIR"

echo "==> Ensuring database '$PGDATABASE' exists"
if ! psql -d postgres -tAc "SELECT 1 FROM pg_database WHERE datname = '$PGDATABASE'" | grep -q 1; then
  createdb "$PGDATABASE"
  echo "    created"
else
  echo "    already exists"
  if [ "${RESET_DB:-0}" = "1" ]; then
    echo "    RESET_DB=1 — dropping and recreating"
    dropdb "$PGDATABASE"
    createdb "$PGDATABASE"
  fi
fi

# setup.sql is a one-shot "full schema + seed" script (not idempotent).
# Only apply it when the schema is not present yet, otherwise every restart fails.
SCHEMA_APPLIED="$(psql -d "$PGDATABASE" -tAc "SELECT 1 FROM information_schema.tables WHERE table_schema = 'public' AND table_name = 'clients'" | tr -d '[:space:]')"
if [ "$SCHEMA_APPLIED" = "1" ]; then
  echo "==> Schema already applied (skip setup.sql — use RESET_DB=1 to start fresh)"
else
  echo "==> Applying schema (supabase/setup.sql)"
  psql -d "$PGDATABASE" -v ON_ERROR_STOP=1 -q -f supabase/setup.sql
fi

echo "==> Ensuring Postgres roles"
psql -d "$PGDATABASE" -v ON_ERROR_STOP=0 -q <<'SQL'
DO $$ BEGIN IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname='anon') THEN CREATE ROLE anon NOLOGIN; END IF; END $$;
DO $$ BEGIN IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname='authenticated') THEN CREATE ROLE authenticated NOLOGIN; END IF; END $$;
DO $$ BEGIN IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname='service_role') THEN CREATE ROLE service_role NOLOGIN BYPASSRLS; END IF; END $$;
GRANT USAGE ON SCHEMA public TO anon, authenticated, service_role;
GRANT ALL ON ALL TABLES IN SCHEMA public TO anon, authenticated, service_role;
GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated, service_role;
GRANT ALL ON ALL FUNCTIONS IN SCHEMA public TO anon, authenticated, service_role;
ALTER ROLE service_role BYPASSRLS;
SQL

echo "==> Generating local JWT tokens"
read -r ANON_TOKEN SERVICE_TOKEN < <(node -e '
const crypto = require("crypto");
const secret = process.argv[1];
function make(role) {
  const header = Buffer.from(JSON.stringify({ alg: "HS256", typ: "JWT" })).toString("base64url");
  const payload = Buffer.from(JSON.stringify({
    role,
    iss: "supabase",
    iat: Math.floor(Date.now() / 1000),
    exp: Math.floor(Date.now() / 1000) + 31536000,
  })).toString("base64url");
  const signature = crypto.createHmac("sha256", secret).update(`${header}.${payload}`).digest("base64url");
  return `${header}.${payload}.${signature}`;
}
console.log(make("anon") + " " + make("service_role"));
' "$JWT_SECRET")

echo "==> Writing .env.local"
cat > .env.local <<EOF
# Local development — Postgres + PostgREST (generated by scripts/start-local.sh)
ADMIN_USERNAME=${ADMIN_USERNAME}
ADMIN_PASSWORD=${ADMIN_PASSWORD}
ADMIN_SESSION_SECRET=local-session-secret-change-me-1234567890
NEXT_PUBLIC_APP_NAME=CodeWizard
NEXT_PUBLIC_APP_URL=${APP_URL}
APP_URL=${APP_URL}
APP_TIMEZONE=Asia/Kolkata
NODE_ENV=development

NEXT_PUBLIC_SUPABASE_URL=http://localhost:${PROXY_PORT}
NEXT_PUBLIC_SUPABASE_ANON_KEY=${ANON_TOKEN}
SUPABASE_SERVICE_ROLE_KEY=${SERVICE_TOKEN}

LICENSE_SIGNING_SECRET=local-license-secret-change-me-1234567890
CRON_SECRET=local-cron-secret

RAZORPAY_ENABLED=false
EOF

# Stop any previous local stack
pkill -f "postgrest" 2>/dev/null || true
pkill -f "local-supabase-proxy.js" 2>/dev/null || true
sleep 1

echo "==> Starting PostgREST on :${BACKEND_PORT}"
PGRST_DB_URI="postgres://${PGUSER}@${PGHOST}:${PGPORT}/${PGDATABASE}" \
PGRST_DB_SCHEMAS=public \
PGRST_DB_ANON_ROLE=anon \
PGRST_JWT_SECRET="$JWT_SECRET" \
PGRST_SERVER_PORT="$BACKEND_PORT" \
PGRST_DB_USE_LEGACY_GUCS=false \
postgrest &
PGRST_PID=$!

echo "==> Starting local Supabase proxy on :${PROXY_PORT}"
PROXY_PORT="$PROXY_PORT" BACKEND_PORT="$BACKEND_PORT" node scripts/local-supabase-proxy.js &
PROXY_PID=$!

cleanup() {
  echo ""
  echo "==> Stopping local stack (PostgREST $PGRST_PID, proxy $PROXY_PID)"
  kill "$PROXY_PID" "$PGRST_PID" 2>/dev/null || true
  exit 0
}
trap cleanup INT TERM

sleep 3
echo ""
echo "==============================================================="
echo "  CodeWizard local stack is starting"
echo "  App:      ${APP_URL}"
echo "  Proxy:    http://localhost:${PROXY_PORT}  (Supabase URL)"
echo "  PostgREST:http://localhost:${BACKEND_PORT}"
echo "  Database: ${PGDATABASE}"
echo "  Login:    ${ADMIN_USERNAME} / ${ADMIN_PASSWORD}"
echo "==============================================================="
echo ""

npm run dev -- -p "$APP_PORT"
